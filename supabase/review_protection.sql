-- =========================================================
-- Amna's Edit - Review privacy + abuse protection
-- Run ONCE in the Supabase SQL Editor.
--
-- This migration:
-- 1. Enforces review text/name limits in the database.
-- 2. Stops browsers from inserting reviews directly.
-- 3. Exposes approved reviews through a privacy-safe view that
--    does NOT include customer_name.
-- 4. Adds a private short-term rate-limit table used only by
--    the server-side /api/reviews route.
-- =========================================================

begin;

-- Future review rows must respect the same limits as the UI.
-- NOT VALID means historical rows are not blocked if older
-- data happened to exceed these limits; new/updated rows are.
alter table public.product_reviews
  drop constraint if exists product_reviews_customer_name_length_check,
  drop constraint if exists product_reviews_review_text_length_check;

alter table public.product_reviews
  add constraint product_reviews_customer_name_length_check
    check (
      char_length(btrim(customer_name)) between 1 and 80
    ) not valid,
  add constraint product_reviews_review_text_length_check
    check (
      char_length(btrim(review_text)) between 5 and 1000
    ) not valid;

-- Private rate-limit log. Raw IP addresses are never stored.
create table if not exists public.review_submission_attempts (
  id bigint generated by default as identity primary key,
  fingerprint_hash text not null,
  product_id uuid not null
    references public.products(id)
    on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists
  review_submission_attempts_fingerprint_created_idx
  on public.review_submission_attempts(
    fingerprint_hash,
    created_at desc
  );

create index if not exists
  review_submission_attempts_product_created_idx
  on public.review_submission_attempts(
    product_id,
    created_at desc
  );

alter table public.review_submission_attempts
  enable row level security;

-- Public approved-review view deliberately omits customer_name.
create or replace view public.public_product_reviews
with (security_barrier = true)
as
select
  id,
  product_id,
  rating,
  review_text,
  is_approved,
  created_at
from public.product_reviews
where is_approved = true;

grant select
  on public.public_product_reviews
  to anon, authenticated;

-- Browsers should not read customer_name from the base table
-- or insert reviews directly anymore.
revoke select, insert
  on public.product_reviews
  from anon;

revoke insert
  on public.product_reviews
  from authenticated;

-- The authenticated owner still needs full moderation access.
grant select, update, delete
  on public.product_reviews
  to authenticated;

-- No browser role can read or write rate-limit records.
revoke all
  on public.review_submission_attempts
  from anon, authenticated;

-- Remove the old public base-table policies.
drop policy if exists
  "Public can view approved product reviews"
  on public.product_reviews;

drop policy if exists
  "Public can submit product reviews"
  on public.product_reviews;

-- Existing owner policies remain unchanged.

commit;
