-- =========================================================
-- Amna's Edit - Privacy-conscious business analytics
-- Phase 7
--
-- Stores product interaction events only.
-- No names, emails, IP addresses, device IDs, or other
-- customer-identifying information are stored.
-- =========================================================

create table if not exists public.analytics_events (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null
    references public.products(id)
    on delete cascade,
  event_type text not null
    check (
      event_type in (
        'product_view',
        'whatsapp_click',
        'instagram_click'
      )
    ),
  created_at timestamptz not null default now()
);

create index if not exists
  analytics_events_created_at_idx
  on public.analytics_events (created_at desc);

create index if not exists
  analytics_events_product_id_idx
  on public.analytics_events (product_id);

create index if not exists
  analytics_events_event_type_idx
  on public.analytics_events (event_type);

alter table public.analytics_events
  enable row level security;

-- Analytics writes now go through /api/analytics using the
-- server-only service-role key. Browsers cannot insert directly.
revoke insert on public.analytics_events
  from anon, authenticated;

-- Only authenticated users who pass the existing is_owner()
-- check can read analytics.
grant select on public.analytics_events
  to authenticated;

revoke update, delete
  on public.analytics_events
  from anon, authenticated;

drop policy if exists
  "Public can record analytics events"
  on public.analytics_events;

drop policy if exists
  "Owner can read analytics events"
  on public.analytics_events;

create policy
  "Owner can read analytics events"
  on public.analytics_events
  for select
  to authenticated
  using (public.is_owner());


-- Private short-term abuse-prevention records.
create table if not exists public.analytics_submission_attempts (
  id bigint generated by default as identity primary key,
  fingerprint_hash text not null,
  product_id uuid not null references public.products(id) on delete cascade,
  event_type text not null check (
    event_type in ('product_view', 'whatsapp_click', 'instagram_click')
  ),
  created_at timestamptz not null default now()
);

create index if not exists analytics_attempts_fingerprint_created_idx
  on public.analytics_submission_attempts(fingerprint_hash, created_at desc);

alter table public.analytics_submission_attempts enable row level security;
revoke all on public.analytics_submission_attempts from anon, authenticated;

-- =========================================================
-- ATOMIC SERVER-SIDE ANALYTICS RECORDER
-- =========================================================

create or replace function public.record_analytics_event_secure(
  p_product_id uuid,
  p_event_type text,
  p_fingerprint_hash text
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := now();
  v_hour_count integer := 0;
  v_hour_limit integer;
  v_duplicate_window interval;
  v_lock_key bigint;
begin
  if p_event_type not in (
    'product_view',
    'whatsapp_click',
    'instagram_click'
  ) then
    return 'invalid';
  end if;

  if not exists (
    select 1 from public.products where id = p_product_id
  ) then
    return 'not_found';
  end if;

  if p_event_type = 'product_view' then
    v_hour_limit := 120;
    v_duplicate_window := interval '30 seconds';
  else
    v_hour_limit := 30;
    v_duplicate_window := interval '10 seconds';
  end if;

  v_lock_key := hashtextextended(
    p_fingerprint_hash || '|' || p_event_type,
    0
  );

  perform pg_advisory_xact_lock(v_lock_key);

  select count(*)
  into v_hour_count
  from public.analytics_submission_attempts
  where fingerprint_hash = p_fingerprint_hash
    and event_type = p_event_type
    and created_at >= v_now - interval '1 hour';

  if v_hour_count >= v_hour_limit then
    return 'rate_limited';
  end if;

  if exists (
    select 1
    from public.analytics_submission_attempts
    where fingerprint_hash = p_fingerprint_hash
      and product_id = p_product_id
      and event_type = p_event_type
      and created_at >= v_now - v_duplicate_window
  ) then
    return 'duplicate';
  end if;

  insert into public.analytics_submission_attempts (
    fingerprint_hash,
    product_id,
    event_type,
    created_at
  )
  values (
    p_fingerprint_hash,
    p_product_id,
    p_event_type,
    v_now
  );

  insert into public.analytics_events (
    product_id,
    event_type,
    created_at
  )
  values (
    p_product_id,
    p_event_type,
    v_now
  );

  delete from public.analytics_submission_attempts
  where created_at < v_now - interval '7 days';

  return 'recorded';
end;
$$;

revoke all
  on function public.record_analytics_event_secure(uuid, text, text)
  from public, anon, authenticated;

grant execute
  on function public.record_analytics_event_secure(uuid, text, text)
  to service_role;

